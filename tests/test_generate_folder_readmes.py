import json
import sys
import tempfile
import unittest
from pathlib import Path

from _loader import load_tool

gfr = load_tool("generate_folder_readmes")

MINIMAL_META = {
    "category": "IT Security",
    "templates": [
        {"filename": "a.html", "name": "T1", "attack_vector": "credential_harvest",
         "difficulty": "beginner", "estimated_click_rate": "40-60%"},
    ],
}

FULL_META = {
    "category": "IT Security",
    "industry": "Technology",
    "description": "Sample category.",
    "templates": [
        {"filename": "a.html", "name": "T1", "attack_vector": "credential_harvest",
         "difficulty": "beginner", "estimated_click_rate": "40-60%",
         "gophish_variables": ["{{.URL}}", "{{.Tracker}}"],
         "education_page": "education/edu.html",
         "suggested_subject_lines": ["Subj One", "Subj Two"],
         "notes": "Some operator note."},
    ],
}


class RenderChecks(unittest.TestCase):
    def test_autogen_header_present(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertIn("AUTOGENERATED by tools/generate_folder_readmes.py", out)

    def test_title_uses_category_and_dir_name(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertIn("# `it-security` — IT Security templates", out)

    def test_falls_back_to_dir_name_when_no_category(self):
        meta = {"templates": []}
        out = gfr.render("it-security", meta)
        self.assertIn("# `it-security` — it-security templates", out)

    def test_industry_and_language_bits_included_when_present(self):
        meta = dict(FULL_META, language="pt-BR")
        out = gfr.render("it-security", meta)
        self.assertIn("**Industry:** Technology", out)
        self.assertIn("**Language:** pt-BR", out)

    def test_industry_and_language_bits_omitted_when_absent(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertNotIn("**Industry:**", out)
        self.assertNotIn("**Language:**", out)

    def test_description_included_when_present(self):
        out = gfr.render("it-security", FULL_META)
        self.assertIn("Sample category.", out)

    def test_summary_table_row_for_template(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertIn(
            "| T1 | [`a.html`](a.html) | credential_harvest | beginner | 40-60% |", out)

    def test_missing_fields_fallback_to_em_dash(self):
        meta = {"templates": [{}]}
        out = gfr.render("it-security", meta)
        self.assertIn("| — | [`—`]() | — | — | — |", out)

    def test_gophish_variables_listed(self):
        out = gfr.render("it-security", FULL_META)
        self.assertIn("**GoPhish variables:** `{{.URL}}` `{{.Tracker}}`", out)

    def test_gophish_variables_omitted_when_absent(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertNotIn("**GoPhish variables:**", out)

    def test_education_page_link_included_when_present(self):
        out = gfr.render("it-security", FULL_META)
        self.assertIn("**Paired training page:** [`education/edu.html`](education/edu.html)", out)

    def test_education_page_omitted_when_absent(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertNotIn("**Paired training page:**", out)

    def test_suggested_subject_lines_listed(self):
        out = gfr.render("it-security", FULL_META)
        self.assertIn("- Subj One", out)
        self.assertIn("- Subj Two", out)

    def test_notes_included_when_present(self):
        out = gfr.render("it-security", FULL_META)
        self.assertIn("**Operator notes:** Some operator note.", out)

    def test_notes_omitted_when_absent(self):
        out = gfr.render("it-security", MINIMAL_META)
        self.assertNotIn("**Operator notes:**", out)

    def test_no_templates_still_renders(self):
        out = gfr.render("it-security", {"templates": []})
        self.assertIn("## Templates", out)
        self.assertIn("## Template details", out)

    def test_output_is_deterministic_single_trailing_newline(self):
        out = gfr.render("it-security", FULL_META)
        self.assertTrue(out.endswith("\n"))
        self.assertFalse(out.endswith("\n\n"))
        # No line should carry trailing whitespace before its newline.
        for line in out.split("\n"):
            self.assertEqual(line, line.rstrip())

    def test_render_is_idempotent(self):
        # Same input must always produce byte-identical output — this is
        # what makes `--check` a reliable CI staleness gate.
        self.assertEqual(gfr.render("it-security", FULL_META), gfr.render("it-security", FULL_META))


class LoadCategories(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self._orig_root = gfr.ROOT
        gfr.ROOT = self.root

        (self.root / "it-security").mkdir()
        (self.root / "it-security" / "metadata.json").write_text(json.dumps(MINIMAL_META))

        (self.root / "financial").mkdir()
        (self.root / "financial" / "metadata.json").write_text(json.dumps(
            {"category": "Financial", "templates": []}))

        for skip in gfr.SKIP_DIRS:
            (self.root / skip).mkdir(exist_ok=True)
            (self.root / skip / "metadata.json").write_text(json.dumps(
                {"category": skip, "templates": []}))

        (self.root / "broken").mkdir()
        (self.root / "broken" / "metadata.json").write_text("{not valid json")

    def tearDown(self):
        gfr.ROOT = self._orig_root
        self.tmp.cleanup()

    def test_skips_non_category_dirs(self):
        names = [name for name, _ in gfr.load_categories()]
        for skip in gfr.SKIP_DIRS:
            self.assertNotIn(skip, names)

    def test_skips_invalid_json_without_crashing(self):
        names = [name for name, _ in gfr.load_categories()]
        self.assertNotIn("broken", names)

    def test_returns_valid_categories_sorted_by_dir_name(self):
        names = [name for name, _ in gfr.load_categories()]
        self.assertEqual(names, ["financial", "it-security"])


class MainCheckMode(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self._orig_root = gfr.ROOT
        self._orig_argv = sys.argv
        gfr.ROOT = self.root

        (self.root / "it-security").mkdir()
        (self.root / "it-security" / "metadata.json").write_text(json.dumps(MINIMAL_META))

    def tearDown(self):
        gfr.ROOT = self._orig_root
        sys.argv = self._orig_argv
        self.tmp.cleanup()

    def _readme(self):
        return self.root / "it-security" / "README.md"

    def test_default_writes_readme(self):
        sys.argv = ["generate_folder_readmes.py"]
        gfr.main()
        self.assertTrue(self._readme().exists())
        self.assertIn("IT Security templates", self._readme().read_text())

    def test_check_fails_when_readme_missing(self):
        sys.argv = ["generate_folder_readmes.py", "--check"]
        with self.assertRaises(SystemExit) as cm:
            gfr.main()
        self.assertNotEqual(cm.exception.code, 0)

    def test_check_passes_when_up_to_date(self):
        expected = gfr.render("it-security", MINIMAL_META)
        self._readme().write_text(expected)
        sys.argv = ["generate_folder_readmes.py", "--check"]
        try:
            gfr.main()
        except SystemExit as e:
            self.fail(f"--check should pass on an up-to-date README, exited with {e.code}")

    def test_check_fails_when_readme_stale(self):
        self._readme().write_text("stale content\n")
        sys.argv = ["generate_folder_readmes.py", "--check"]
        with self.assertRaises(SystemExit) as cm:
            gfr.main()
        self.assertNotEqual(cm.exception.code, 0)

    def test_stdout_mode_does_not_write_file(self):
        sys.argv = ["generate_folder_readmes.py", "--stdout"]
        gfr.main()
        self.assertFalse(self._readme().exists())


if __name__ == "__main__":
    unittest.main()
